#!/usr/bin/env python3
"""Build native tgo distributions and prepare release assets."""

import argparse
import hashlib
import json
import os
from pathlib import Path
import platform
import re
import shutil
import subprocess
import tarfile
import tempfile


TARGETS = [(system, arch) for system in ("darwin", "linux") for arch in ("amd64", "arm64")]


def run(*args, **kwargs):
    return subprocess.check_output(args, text=True, **kwargs).strip()


def build(args, version):
    repo = Path(__file__).resolve().parents[2]
    system = {"Darwin": "darwin", "Linux": "linux"}[platform.system()]
    arch = {"x86_64": "amd64", "aarch64": "arm64", "arm64": "arm64"}[platform.machine()]
    commit = run("git", "rev-parse", "HEAD", cwd=repo)
    timestamp = run("git", "show", "-s", "--format=%cI", "HEAD", cwd=repo)
    output = args.output.resolve()
    output.mkdir(parents=True, exist_ok=True)

    # A tracked snapshot excludes worktree caches, editor files and build output.
    with tempfile.TemporaryDirectory(prefix="tgo-release-") as temporary:
        stage = Path(temporary)
        snapshot = stage / "source.tar"
        subprocess.run(["git", "archive", "--format=tar", "-o", str(snapshot), "HEAD"], cwd=repo, check=True)
        root = stage / "go"
        root.mkdir()
        subprocess.run(["tar", "-xf", str(snapshot), "-C", str(root)], check=True)
        minor = re.search(r"const Version = (\d+)", (root / "src/internal/goversion/goversion.go").read_text())[1]
        goversion = f"go1.{minor}-devel_tgo{version}-{commit[:12]}"
        (root / "VERSION").write_text(f"{goversion}\ntime {timestamp}\n")
        defaults = root / "go.env"
        defaults.write_text(defaults.read_text().replace("GOTOOLCHAIN=auto", "GOTOOLCHAIN=local"))
        (root / "TGO_RELEASE.json").write_text(json.dumps({
            "tag": args.tag, "commit": commit, "go_version": goversion,
            "os": system, "arch": arch,
        }, indent=2) + "\n")
        env = os.environ.copy()
        for key in ("GOROOT", "GOOS", "GOARCH", "GOFLAGS", "GOEXPERIMENT", "GOBIN"):
            env.pop(key, None)
        env.update(GOTOOLCHAIN="local", GOENV="off", GO_BUILDER_NAME="tgo-release")
        subprocess.run(["bash", "make.bash", "-distpack"], cwd=root / "src", env=env, check=True)
        archive = root / "pkg/distpack" / f"{goversion}.{system}-{arch}.tar.gz"
        destination = output / f"tgo_{version}_{system}_{arch}.tar.gz"
        shutil.copyfile(archive, destination)
        print(destination)


def prepare(args, version):
    output = args.output.resolve()
    checksums = {}
    manifests = []
    for system, arch in TARGETS:
        name = f"tgo_{version}_{system}_{arch}.tar.gz"
        archive = output / name
        with archive.open("rb") as source:
            checksums[system, arch] = hashlib.file_digest(source, "sha256").hexdigest()
        with tarfile.open(archive) as packed:
            manifest = json.load(packed.extractfile("go/TGO_RELEASE.json"))
        if (manifest["tag"], manifest["os"], manifest["arch"]) != (args.tag, system, arch):
            raise ValueError(f"release metadata does not match {name}")
        manifests.append(manifest)
    if len({(m["commit"], m["go_version"]) for m in manifests}) != 1:
        raise ValueError("all archives must come from the same revision and Go version")
    base = f"https://github.com/{args.repository}/releases/download/{args.tag}"
    formula = [
        "# Generated by misc/tgo/release.py; installs precompiled toolchains.",
        "class Tgo < Formula",
        '  desc "Go toolchain with Temporal workflow isolates"',
        f'  homepage "https://github.com/{args.repository}"',
        f'  version "{version}"',
        '  license "BSD-3-Clause"',
    ]
    for system in ("darwin", "linux"):
        formula.append(f"  on_{'macos' if system == 'darwin' else 'linux'} do")
        for index, arch in enumerate(("arm64", "amd64")):
            formula.append("    if Hardware::CPU.arm?" if index == 0 else "    else")
            formula.append(f'      url "{base}/tgo_{version}_{system}_{arch}.tar.gz"')
            formula.append(f'      sha256 "{checksums[system, arch]}"')
        formula.extend(["    end", "  end"])
    formula.extend([
        "", "  def install", "    libexec.install Dir[\"*\"]",
        '    (bin/"tgo").write_env_script libexec/"bin/tgo",',
        '                                GOROOT: libexec, GOTOOLCHAIN: "local"',
        "  end", "", "  test do",
        '    assert_match version.to_s, shell_output("#{bin}/tgo version")',
        "  end", "end", "",
    ])
    (output / "tgo.rb").write_text("\n".join(formula))
    shutil.copyfile(Path(__file__).with_name("install.sh"), output / "install.sh")
    (output / "release.json").write_text(json.dumps(manifests, indent=2) + "\n")
    names = [f"tgo_{version}_{system}_{arch}.tar.gz" for system, arch in TARGETS]
    names += ["tgo.rb", "install.sh", "release.json"]
    with (output / "SHA256SUMS").open("w") as sums:
        for name in names:
            with (output / name).open("rb") as asset:
                sums.write(f"{hashlib.file_digest(asset, 'sha256').hexdigest()}  {name}\n")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("command", choices=["build", "prepare"])
    parser.add_argument("tag", help="release tag, for example tgo-v0.1.0")
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--repository", default="mfateev/golang-go")
    args = parser.parse_args()
    if not re.fullmatch(r"tgo-v\d+\.\d+\.\d+(?:-[0-9A-Za-z]+(?:[.-][0-9A-Za-z]+)*)?", args.tag):
        parser.error("tag must have the form tgo-v0.1.0 or tgo-v0.1.0-rc.1")
    if not re.fullmatch(r"[\w.-]+/[\w.-]+", args.repository):
        parser.error("repository must have the form owner/repo")
    {"build": build, "prepare": prepare}[args.command](args, args.tag.removeprefix("tgo-v"))


if __name__ == "__main__":
    main()
